package escpos

import "sync"

// Codepage is an ESC/POS character table.
type Codepage int

// Supported codepages. The values are the ESC t n table numbers.
const (
	CP437   Codepage = 0
	CP858   Codepage = 19
	WPC1252 Codepage = 16
)

// Code is the n of ESC t n.
func (c Codepage) Code() byte { return byte(c) }

// ParseCodepage maps a name (cp437, cp858, wpc1252) to a Codepage.
func ParseCodepage(name string) (Codepage, bool) {
	switch name {
	case "cp437", "CP437":
		return CP437, true
	case "cp858", "CP858":
		return CP858, true
	case "wpc1252", "WPC1252", "cp1252", "windows-1252":
		return WPC1252, true
	}
	return CP437, false
}

