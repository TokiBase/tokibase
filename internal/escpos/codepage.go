func (c Codepage) decode(b byte) rune {
	if b < 0x80 {
		return rune(b)
	}
	switch c {
	case CP858:
		return cp858High[b-0x80]
	case WPC1252:
		if b < 0xA0 {
			return wpc1252Low[b-0x80]
		}
		return rune(b)
	}
	return cp437High[b-0x80]
}

var (
	revOnce [3]sync.Once
	rev     [3]map[rune]byte
)

func (c Codepage) index() int {
	switch c {
	case CP858:
		return 1
	case WPC1252:
		return 2
	}
	return 0
}

func (c Codepage) reverse() map[rune]byte {
	i := c.index()
	revOnce[i].Do(func() {
		m := make(map[rune]byte, 128)
		for b := 0x80; b < 0x100; b++ {
			if r := c.decode(byte(b)); r != 0 {
				if _, dup := m[r]; !dup {
					m[r] = byte(b)
				}
			}
		}
		rev[i] = m
	})
	return rev[i]
}

// Encode converts s to the codepage. Unmappable runes become '?', control
// characters other than LF and TAB are dropped, CR is dropped.
func (c Codepage) Encode(s string) []byte {
	out := make([]byte, 0, len(s))
	var m map[rune]byte
	for _, r := range s {
		switch {
		case r == '\n' || r == '\t':
			out = append(out, byte(r))
		case r < 0x20 || r == 0x7F:
		case r < 0x80:
			out = append(out, byte(r))
		default:
			if m == nil {
				m = c.reverse()
			}
			if b, ok := m[r]; ok {
				out = append(out, b)
			} else {
				out = append(out, '?')
			}
		}
	}
	return out
}
